    const newXml = xmlFromBlocks(xml, list)
    const m = new Map(files); m.set(proxyPath, newXml); setFiles(m); setCurrentPath(proxyPath)
    setStatus({ kind: 'ok', msg: `Reordered flows (moved ${fromIdx + 1} → ${toIdx + 1})` })
